import { chromium } from 'playwright-core'
const log = (m) => console.log('✔', m)
const expect = (c, m) => { if (!c) throw new Error('FALLÓ: ' + m); log(m) }
const b = await chromium.launch({ channel: 'msedge' })
const errors = []
const URL = 'http://localhost:4173/'
const money = (t) => Number(t.replace(/[^0-9.\-−]/g, '').replace('−', '-'))
async function newPage(w, h, scheme = 'light') {
  const ctx = await b.newContext({ viewport: { width: w, height: h }, locale: 'es-MX', timezoneId: 'America/Mexico_City', colorScheme: scheme })
  const p = await ctx.newPage()
  p.on('pageerror', (e) => errors.push(e.message)); p.on('console', (m) => m.type() === 'error' && errors.push(m.text()))
  return p
}
const kpi = async (p, label) => money(await p.getByRole('button', { name: new RegExp('^' + label + ':') }).locator('.v').innerText())

